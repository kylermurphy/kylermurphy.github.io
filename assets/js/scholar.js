/* Live Google Scholar numbers.
   Fills [data-scholar="group.field"], [data-scholar-since] and [data-scholar-updated]
   from scholar.json (generated by github.com/kylermurphy/scholar_plot).
   Build-time fallbacks in the markup stay untouched if anything fails. */
(function () {
  'use strict';

  var SCHOLAR_URL = 'https://raw.githubusercontent.com/kylermurphy/scholar_plot/master/data/scholar.json';
  var MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

  function each(selector, fn) {
    var nodes = document.querySelectorAll(selector);
    for (var i = 0; i < nodes.length; i++) { fn(nodes[i]); }
  }

  function lookup(obj, path) {
    var parts = path.split('.');
    for (var i = 0; i < parts.length; i++) {
      if (obj === null || typeof obj !== 'object' || !(parts[i] in obj)) { return undefined; }
      obj = obj[parts[i]];
    }
    return obj;
  }

  function formatNumber(n) {
    try { return n.toLocaleString('en-US'); } catch (e) { return String(n); }
  }

  function formatUpdated(iso) {
    var m = /^(\d{4})-(\d{2})/.exec(String(iso || ''));
    if (!m) { return ''; }
    var month = parseInt(m[2], 10);
    if (month < 1 || month > 12) { return ''; }
    return MONTHS[month - 1] + ' ' + m[1];
  }

  function apply(data) {
    var totals = data && data.totals;
    if (!totals || typeof totals !== 'object') { throw new Error('scholar.json has no totals'); }

    each('[data-scholar]', function (el) {
      var value = lookup(totals, el.getAttribute('data-scholar') || '');
      if (typeof value === 'number' && isFinite(value)) { el.textContent = formatNumber(value); }
    });

    if (typeof data.since_year === 'number' && isFinite(data.since_year)) {
      each('[data-scholar-since]', function (el) { el.textContent = String(data.since_year); });
    }

    var updated = formatUpdated(data.updated);
    if (updated) {
      each('[data-scholar-updated]', function (el) { el.textContent = updated; });
    }
  }

  function run() {
    if (!document.querySelector('[data-scholar], [data-scholar-since], [data-scholar-updated]')) { return; }
    if (typeof window.fetch !== 'function') { return; }
    try {
      window.fetch(SCHOLAR_URL, { cache: 'no-cache' })
        .then(function (res) {
          if (!res.ok) { throw new Error('HTTP ' + res.status); }
          return res.json();
        })
        .then(apply)
        ['catch'](function (err) {
          if (window.console && console.warn) { console.warn('scholar.js: using fallback numbers (' + (err && err.message ? err.message : err) + ')'); }
        });
    } catch (err) {
      if (window.console && console.warn) { console.warn('scholar.js: using fallback numbers'); }
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', run);
  } else {
    run();
  }
}());
